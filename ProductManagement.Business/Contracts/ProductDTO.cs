using ProductManagement.Business.Models;

namespace ProductManagement.Business.Contracts
{
    public class ProductDTO
    {
        public int Id { get; set; }
        public string Name { get; set; }
        public string? Description { get; set; }
        public decimal Price { get; set; }
        public int Stock { get; set; }
        public DateTime CreatedAt { get; set; }
        public DateTime? UpdatedAt { get; set; }

        public static ProductDTO FromBusinessModel(ProductBusinessModel product)
        {
            return new ProductDTO
            {
                Id = product.Id,
                Name = product.Name,
                Description = product.Description,
                Price = product.Price,
                Stock = product.Stock,
                CreatedAt = product.CreatedAt.ToLocalTime(),
                UpdatedAt = product.UpdatedAt?.ToLocalTime()
            };
        }
    }
}
